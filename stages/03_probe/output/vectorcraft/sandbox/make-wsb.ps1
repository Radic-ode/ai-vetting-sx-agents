# make-wsb.ps1 - runs on the HOST. Writes one Windows Sandbox config per probe into .\wsb\ and an
# empty log folder per probe into ..\logs\<probe>\. Writes files only; starts nothing.
# Re-run it before every probe session: a probe's log folder must start empty. A finished probe's folder
# (it has DONE.txt) is kept as evidence; to run that probe again, pass -Redo <probe>.
param([string[]]$Redo = @())
$here  = $PSScriptRoot
$tools = Join-Path $here 'tools'
$logs  = Join-Path (Split-Path $here) 'logs'
$wsb   = Join-Path $here 'wsb'
New-Item -ItemType Directory -Force $wsb | Out-Null

$networked = 'net-out', 'self-update'
$probes = 'baseline','install','persist','net-out','self-update','net-listen','fs-read','fs-write','exec','secrets','agent-text'

foreach ($p in $probes) {
  $log = Join-Path $logs $p
  $keep = (Test-Path (Join-Path $log 'DONE.txt')) -and ($p -notin $Redo)
  if ($keep) { Write-Host "kept $p (finished; -Redo $p to run it again)" }
  else {
    if (Test-Path $log) { Remove-Item -Recurse -Force $log }
    New-Item -ItemType Directory -Force $log | Out-Null }
  $out = ''
  if ($p -eq 'fs-write') {   # the grant: one writable folder, kept apart from the log folder
    $o = Join-Path $logs 'fs-write-out'
    if (-not $keep) {
      if (Test-Path $o) { Remove-Item -Recurse -Force $o }
      New-Item -ItemType Directory -Force $o | Out-Null }
    $out = @"

    <MappedFolder><HostFolder>$o</HostFolder><SandboxFolder>C:\probe\out</SandboxFolder><ReadOnly>false</ReadOnly></MappedFolder>
"@
  }
  $net = if ($p -in $networked) { 'Enable' } else { 'Disable' }
  @"
<!-- VectorCraft 0.17.0 probe: $p   (generated by make-wsb.ps1; double-click to run) -->
<Configuration>
  <Networking>$net</Networking>
  <vGPU>Disable</vGPU>
  <ClipboardRedirection>Disable</ClipboardRedirection>
  <PrinterRedirection>Disable</PrinterRedirection>
  <AudioInput>Disable</AudioInput>
  <VideoInput>Disable</VideoInput>
  <MemoryInMB>4096</MemoryInMB>
  <MappedFolders>
    <MappedFolder><HostFolder>$tools</HostFolder><SandboxFolder>C:\probe\tools</SandboxFolder><ReadOnly>true</ReadOnly></MappedFolder>
    <MappedFolder><HostFolder>$log</HostFolder><SandboxFolder>C:\probe\logs</SandboxFolder><ReadOnly>false</ReadOnly></MappedFolder>$out
  </MappedFolders>
  <LogonCommand>
    <Command>powershell.exe -NoProfile -ExecutionPolicy Bypass -Command "Start-Process powershell.exe -ArgumentList '-NoProfile -ExecutionPolicy Bypass -NoExit -File C:\probe\tools\probe.ps1 -Probe $p'"</Command>
  </LogonCommand>
</Configuration>
"@ | Set-Content -Encoding UTF8 (Join-Path $wsb "$p.wsb")
}
Write-Host "wrote $($probes.Count) .wsb files to $wsb and empty log folders under $logs"
